export function quoteFor(shot: GalleryShot) {
  const title = shot.title.toLowerCase();
  if (title.includes("bifold")) return "Bifold doors" as const;
  if (title.includes("french")) return "French doors" as const;
  if (title.includes("pivot") || title.includes("sliding door") || title.includes("barn")) {
    return "Pivot or sliding doors" as const;
  }
  if (shot.kind === "Windows") return "Timber windows" as const;
  if (
    title.includes("heritage") ||
    title.includes("federation") ||
    title.includes("castle") ||
    title.includes("medieval")
  ) {
    return "Heritage or Federation door" as const;
  }
  return "Entrance door" as const;
}

